/// checks if two words have only a single letter different
fn check_one_letter_diff(word1: &str, word2: &str) -> bool{
    let mut count: i8 = 0;
    for (c1, c2) in word1.chars().zip(word2.chars()) {
        if c1 != c2{
            count += 1;
        }
    }

    return count == 1;
}

/// returns a vector with all the valid and efficient words possible for the next step
fn find_valid_words<'a>(curr_word: &WordStep, words: &'a [WordStep]) -> Vec<&'a WordStep>{
    let valid_words: Vec<&'a WordStep> = words
        .iter()
        .filter(|wordstep| (wordstep.steps == (curr_word.steps - 1)) && (check_one_letter_diff(wordstep.word, curr_word.word)))
        .collect();
    
    return valid_words;
}

/// keeps looking for the next step until it finds the goal, then returns the path it found
fn solve_puzzle(starting_word: &'static WordStep) -> Vec<&'static WordStep> {
    let mut curr_word = starting_word;
    let mut path: Vec<&'static WordStep> = Vec::new();
    path.push(curr_word);
    
    while curr_word.word != "poop" {
        let next_word = find_valid_words(curr_word, &WORDS)[0];
        path.push(next_word);
        curr_word = next_word;
    }
    
    return path;
}

