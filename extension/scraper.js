let wasmModule = null;
let precalculatedPath = null;

function getStartingWord() {
  const scroll_container = document.getElementById("ScrollContainer");
  const first_row = scroll_container.querySelector(".Row");
  const starting_letters = first_row.querySelectorAll(".Box")

  if (starting_letters.length !== 4) {
    console.log("Error: Starting word not found")
    return null;
  }

  let starting_word = "";
  for (let letter of starting_letters) {
    if (letter.textContent !== "") {
      starting_word += letter.textContent.trim()
    }
  }
  
  return starting_word.toLowerCase()
}

(async () => {
  try {
    // Get the URLs for the files generated by wasm-pack
    const wasmWrapperUrl = chrome.runtime.getURL('pkg/poople_solver.js');
    const wasmFileUrl = chrome.runtime.getURL('pkg/poople_solver_bg.wasm');
    
    // Import the wrapper and initialize the WebAssembly binary
    const loadedModule = await import(wasmWrapperUrl);
    await loadedModule.default(wasmFileUrl);
    wasmModule = loadedModule;
    console.log("Wasm solver loaded."); // Breadcrumb

    // Scrape the word from the interface
    const startingWord = getStartingWord()

    // Call Rust function
    if (startingWord) {
      precalculatedPath = wasmModule.find_quickest_path(startingWord);
    }

  } catch (error) {
    console.error("Error loading Wasm or solving:", error);
  }
})();

const sleep = (ms) => new Promise(resolve => setTimeout(resolve, ms));

function pressKey(keyChar) {
  const keyUpper = keyChar.toUpperCase();
  const code = keyUpper.charCodeAt(0);
  
  const keydown = new KeyboardEvent('keydown', { key: keyChar, code: `Key${keyUpper}`, keyCode: code, which: code, bubbles: true, cancelable: true });
  const keyup = new KeyboardEvent('keyup', { key: keyChar, code: `Key${keyUpper}`, keyCode: code, which: code, bubbles: true, cancelable: true });
  
  document.dispatchEvent(keydown);
  document.dispatchEvent(keyup);
}

async function typeWord(word) {
  for (let i = 0; i < word.length; i++) {
    pressKey(word[i]);
    await sleep(100); 
  }
  await sleep(100);
  pressKey('Enter');
}

chrome.runtime.onMessage.addListener((request, sender, sendResponse) => {
  if (request.command === "run_solve") {
    sendResponse({ success: true }); 
    
    // Do the typing locally
    if (precalculatedPath && precalculatedPath.length > 0) {
      (async () => {
        for (let i = 1; i < precalculatedPath.length; i++) {
          await typeWord(precalculatedPath[i]);
          await sleep(500);
        }
      })();
    }
  }
  return true; 
});